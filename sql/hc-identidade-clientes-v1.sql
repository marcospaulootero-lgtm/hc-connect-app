-- HC_IDENTIDADE_CLIENTES_V1
create table if not exists public.cliente_aliases (
  id bigint generated by default as identity primary key,
  alias text not null,
  alias_normalizado text not null unique,
  nome_oficial text not null,
  nome_oficial_normalizado text not null,
  criado_por uuid null,
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now()
);

create index if not exists cliente_aliases_nome_oficial_idx
  on public.cliente_aliases(nome_oficial_normalizado);

alter table public.cliente_aliases enable row level security;

drop policy if exists "cliente_aliases_admin_select" on public.cliente_aliases;
create policy "cliente_aliases_admin_select"
on public.cliente_aliases
for select
to authenticated
using (
  exists (
    select 1
    from public.perfis p
    where p.id = auth.uid()
      and lower(coalesce(p.tipo_acesso, '')) = 'admin'
      and coalesce(p.ativo, true) = true
  )
);

drop policy if exists "cliente_aliases_admin_insert" on public.cliente_aliases;
create policy "cliente_aliases_admin_insert"
on public.cliente_aliases
